def test_hardware_scan_has_deep_dbs_dialogue():
    text = _read(REPORT)
    dbs_section = _section(text, "## 7. 深度 DBS 对话记录")
    rounds = re.findall(r"### Round \d", dbs_section)

    assert len(rounds) >= 6
    assert dbs_section.count("Builder") >= len(rounds)
    assert dbs_section.count("Challenger") >= len(rounds)
    assert dbs_section.count("Revision") >= len(rounds)
    assert dbs_section.count("Judge") >= len(rounds)
    assert "Verdict: Validate Payment Now" in dbs_section


