import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "hardware-engineer-global-opportunity-scan.md"
CONTRACT = ROOT / "docs" / "09-opportunity-scan-quality-contract.md"
TEMPLATE = ROOT / "docs" / "opportunity-scan-template.md"
VALUE_CHAIN_MAP = (
    ROOT
    / "docs"
    / "assets"
    / "opportunity_maps"
    / "hardware-engineer-global-value-chain-map.svg"
)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _section(text: str, heading: str) -> str:
    start = text.index(heading)
    next_heading = text.find("\n## ", start + len(heading))
    if next_heading == -1:
        return text[start:]
    return text[start:next_heading]


def test_quality_contract_and_template_exist_with_required_gates():
    contract = _read(CONTRACT)
    template = _read(TEMPLATE)

    for gate in [
        "Reader Contract",
        "Opportunity Map Gate",
        "Evidence Gate",
        "DBS Dialogue Gate",
        "Candidate Ranking Gate",
        "Action Gate",
        "Artifact Gate",
        "Done Definition",
    ]:
        assert gate in contract

    for visual_requirement in [
        "human-facing visual map",
        "machine-readable structured map",
        "At least 20 plotted opportunities",
        "two-layer mapping",
    ]:
        assert visual_requirement in contract

    for required_section in [
        "Decision Summary",
        "Whole Opportunity Map",
        "Evidence Ledger",
        "Candidate Ranking",
        "DBS Dialogue",
        "Action Plan",
        "Appendix",
    ]:
        assert required_section in template

    assert "image2-generated bitmap" in template
    assert "quadrantChart" in template


def test_hardware_scan_has_whole_map_before_single_recommendation():
    text = _read(REPORT)
    map_section = _section(text, "## 5. 全局机会地图")

    assert text.startswith("<!-- Generated by ODE -->")
    assert VALUE_CHAIN_MAP.exists()
    assert "assets/opportunity_maps/hardware-engineer-global-value-chain-map.svg" in map_section
    assert map_section.count("```mermaid") >= 2
    assert "flowchart LR" in map_section
    assert "quadrantChart" in map_section
    assert "### 候选机会池" in map_section

    quadrant_block = re.search(r"quadrantChart(?P<body>.*?)```", map_section, re.S)
    assert quadrant_block is not None
    plotted_points = re.findall(r'"[^"]+": \[[0-9.]+, [0-9.]+\]', quadrant_block.group("body"))
    assert len(plotted_points) >= 20

    candidate_rows = [
        line
        for line in map_section.splitlines()
        if line.startswith("| ")
        and "---" not in line
        and "Candidate" not in line
        and "机会" not in line
        and "层级" not in line
    ]

    assert len(candidate_rows) >= 24
    assert "Prototype-to-Production Readiness Review" in map_section
    assert "White-label Hardware Export" in map_section
    assert "Self-owned Hardware Product" in map_section
    assert "General AI Hardware Platform" in map_section
    assert "Marketplace for Hardware Suppliers" in map_section
    assert "地图上保留 26 个候选机会" in map_section


